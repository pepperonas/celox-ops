def category_for_description(description: str) -> str | None:
    """Exact match first, then fold-insensitive lookup on EXPENSE_DESCRIPTION_CATEGORY."""
    if description in EXPENSE_DESCRIPTION_CATEGORY:
        return EXPENSE_DESCRIPTION_CATEGORY[description]
    folded = description.casefold()
    for key, value in EXPENSE_DESCRIPTION_CATEGORY.items():
        if key.casefold() == folded:
            return value
    return None


